#!/usr/bin/env python3
"""
Generate realistic mock e-commerce logs for an ELK (Elasticsearch, Logstash, Kibana)
pipeline exercise.

Outputs:
  logs.csv                 Valid CSV events
  logs.jsonl               Valid JSON Lines events (one JSON object per line)
  malformed_logs.jsonl     Intentionally invalid JSON lines for DLQ/error testing

Usage:
  python generate_mock_logs.py
  python generate_mock_logs.py --count 1000 --out-dir data --seed 42
"""

import argparse
import csv
import json
import random
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path


LEVELS = ["INFO", "INFO", "INFO", "WARN", "ERROR", "DEBUG"]
SERVICES = ["web-store", "order-service", "payment-service", "inventory-service"]
EVENTS = [
    "product_view",
    "add_to_cart",
    "checkout_started",
    "order_created",
    "payment_succeeded",
    "payment_failed",
    "stock_warning",
    "user_login",
]
COUNTRIES = [
    ("Tunisia", 36.8065, 10.1815),
    ("France", 48.8566, 2.3522),
    ("Germany", 52.5200, 13.4050),
    ("Italy", 41.9028, 12.4964),
    ("United Kingdom", 51.5072, -0.1276),
]
PRODUCT_IDS = ["PRD-1001", "PRD-1002", "PRD-1003", "PRD-1004", "PRD-1005"]
CURRENCIES = ["TND", "EUR", "USD"]
STATUSES = ["success", "success", "success", "pending", "failed"]


def make_event(index: int, start_time: datetime) -> dict:
    """Create one normalized e-commerce event."""
    event_type = random.choice(EVENTS)
    country, latitude, longitude = random.choice(COUNTRIES)
    level = random.choice(LEVELS)

    # Make event severity consistent with a few important event types.
    if event_type == "payment_failed":
        level = "ERROR"
    elif event_type == "stock_warning":
        level = "WARN"

    quantity = random.randint(1, 5)
    amount = round(random.uniform(10, 800), 2)
    status = random.choice(STATUSES)

    if event_type == "payment_failed":
        status = "failed"

    return {
        "@timestamp": (
            start_time + timedelta(seconds=index * random.randint(1, 20))
        ).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "event_id": str(uuid.uuid4()),
        "level": level,
        "service": random.choice(SERVICES),
        "environment": random.choice(["development", "staging", "production"]),
        "event_type": event_type,
        "user_id": f"USR-{random.randint(1000, 9999)}",
        "session_id": f"SES-{random.randint(100000, 999999)}",
        "order_id": (
            f"ORD-{random.randint(10000, 99999)}"
            if event_type in {"order_created", "payment_succeeded", "payment_failed"}
            else ""
        ),
        "product_id": random.choice(PRODUCT_IDS),
        "quantity": quantity,
        "amount": amount,
        "currency": random.choice(CURRENCIES),
        "status": status,
        "ip": (
            f"192.168.{random.randint(0, 10)}.{random.randint(2, 254)}"
        ),
        "country": country,
        "geo_lat": latitude + random.uniform(-0.05, 0.05),
        "geo_lon": longitude + random.uniform(-0.05, 0.05),
        "tags": ["ecommerce", event_type, level.lower()],
        "message": (
            f"{event_type.replace('_', ' ').capitalize()} event "
            f"generated by {random.choice(SERVICES)}"
        ),
    }


def write_csv(events: list[dict], path: Path) -> None:
    # CSV stores tags as a pipe-separated string; Logstash can split it later.
    fieldnames = list(events[0].keys())
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        for event in events:
            row = event.copy()
            row["tags"] = "|".join(row["tags"])
            writer.writerow(row)


def write_jsonl(events: list[dict], path: Path) -> None:
    with path.open("w", encoding="utf-8") as file:
        for event in events:
            file.write(json.dumps(event, ensure_ascii=False) + "\n")


def write_malformed_json(path: Path) -> None:
    """Write deliberately broken records to test Logstash parsing failures."""
    samples = [
        '{"timestamp": "2026-11-10T10:00:00Z", "level": "ERROR", "message": "Missing closing brace"',
        '{"timestamp": "not-a-date", "level": "INFO", "amount": "not-a-number"}',
        '{"level": "ERROR", "message": "Invalid JSON",}',
        'THIS IS NOT JSON',
    ]
    path.write_text("\n".join(samples) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate mock e-commerce logs for ELK.")
    parser.add_argument("--count", type=int, default=250, help="Number of valid events to generate.")
    parser.add_argument("--out-dir", default="mock-logs", help="Directory for generated files.")
    parser.add_argument("--seed", type=int, default=None, help="Optional random seed for repeatable output.")
    args = parser.parse_args()

    if args.count < 1:
        parser.error("--count must be at least 1")

    if args.seed is not None:
        random.seed(args.seed)

    output_dir = Path(args.out_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    start_time = datetime.now(timezone.utc) - timedelta(days=1)
    events = [make_event(i, start_time) for i in range(args.count)]

    csv_path = output_dir / "logs.csv"
    jsonl_path = output_dir / "logs.jsonl"
    malformed_path = output_dir / "malformed_logs.jsonl"

    write_csv(events, csv_path)
    write_jsonl(events, jsonl_path)
    write_malformed_json(malformed_path)

    print(f"Generated {len(events)} valid events in: {output_dir.resolve()}")
    print(f"  CSV:              {csv_path}")
    print(f"  JSON Lines:       {jsonl_path}")
    print(f"  Malformed JSON:   {malformed_path}")


if __name__ == "__main__":
    main()
